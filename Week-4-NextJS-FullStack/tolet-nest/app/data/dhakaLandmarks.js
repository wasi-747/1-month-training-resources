// Calculate distance in meters
function getDistanceMeters(lat1, lon1, lat2, lon2) {
  const R = 6371e3;
  const φ1 = (lat1 * Math.PI) / 180;
  const φ2 = (lat2 * Math.PI) / 180;
  const Δφ = ((lat2 - lat1) * Math.PI) / 180;
  const Δλ = ((lon2 - lon1) * Math.PI) / 180;

  const a =
    Math.sin(Δφ / 2) * Math.sin(Δφ / 2) +
    Math.cos(φ1) * Math.cos(φ2) * Math.sin(Δλ / 2) * Math.sin(Δλ / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));

  return Math.round(R * c);
}

// Find closest landmark when user drags the map pointer (Foodpanda / Pathao live pin lookup)
export function findClosestDhakaLandmark(lat, lng) {
  if (!lat || !lng) return null;

  let closest = null;
  let minDistance = Infinity;

  for (const landmark of DHAKA_COMPREHENSIVE_LANDMARKS) {
    const dist = getDistanceMeters(lat, lng, landmark.lat, landmark.lng);
    if (dist < minDistance) {
      minDistance = dist;
      closest = { ...landmark, distanceMeters: dist };
    }
  }

  return closest;
}

// Instant Local Search Function (Fuzzy keyword and text matching)
export function searchDhakaLandmarks(query) {
  if (!query || !query.trim()) {
    return DHAKA_COMPREHENSIVE_LANDMARKS.slice(0, 12);
  }

  const cleanQ = query.trim().toLowerCase();

  return DHAKA_COMPREHENSIVE_LANDMARKS.filter((item) => {
    // 1. Direct Name match
    if (item.name.toLowerCase().includes(cleanQ)) return true;
    if (item.shortName.toLowerCase().includes(cleanQ)) return true;
    if (item.area.toLowerCase().includes(cleanQ)) return true;

    // 2. Keyword match (e.g. 'jfp', 'jamuna', 'kfc', 'bfc', 'chillox', 'lake', 'merul', 'hatirjheel')
    if (item.keywords && item.keywords.some((k) => k.includes(cleanQ) || cleanQ.includes(k))) {
      return true;
    }

    // 3. Category match
    if (item.category.toLowerCase().includes(cleanQ)) return true;

    return false;
  });
}
